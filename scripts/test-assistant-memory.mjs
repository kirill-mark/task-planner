import assert from 'node:assert/strict';
import { memoryRequest, scopedNote, activeMemory, noteDate, recallChats } from '../js/assistant-memory.js';
import { readChats, writeChats, beginConversation } from '../js/assistant-chats.js';
const now = Date.parse('2026-10-10T11:32:00Z'), zone='Europe/Moscow';
const actual = 'Я хочу начать сегодня с выхода ролика в Smolenka запомни это';
assert.equal(memoryRequest(actual).fact, 'Я хочу начать сегодня с выхода ролика в Smolenka');
const note = scopedNote(memoryRequest(actual).fact, now, zone);
assert.equal(noteDate(note), '2026-10-10'); assert.ok(note.includes('Smolenka'));
assert.equal(activeMemory([note], '2026-10-10').length, 1);
assert.equal(activeMemory([note], '2026-10-11').length, 0);
assert.equal(memoryRequest('Пожалуйста, запомни: я продюсер').fact, 'я продюсер');
assert.equal(memoryRequest('Я предпочитаю один шаг, запомни пожалуйста').fact, 'Я предпочитаю один шаг');
assert.equal(memoryRequest('не запомни: нет'), null);
assert.equal(memoryRequest('Я не хочу этого, не запомни это'), null);
assert.equal(memoryRequest('Как запомнить мои задачи?'), null);
assert.equal(memoryRequest('Запомни это').fact, null);
assert.equal(noteDate(scopedNote('Я начну завтра со звонка', Date.parse('2026-10-31T20:00:00Z'), zone)), '2026-11-01');
assert.equal(noteDate(scopedNote('Я начну сегодня', Date.parse('2026-10-10T22:00:00Z'), zone)), '2026-10-11');
assert.equal(activeMemory(['Я продюсер'], '2027-01-01').length, 1);
const map = new Map(); const storage={getItem:k=>map.get(k),setItem:(k,v)=>map.set(k,v)};
const book = readChats(storage, 'alice', now);
book.threads[0].messages.push({role:'user', content:actual, at:now});
book.threads[0].messages.push({role:'assistant', content:'Invented dependency!', at:now});
book.memory=[note];
const second=beginConversation(book);
assert.equal(second.messages.length, 0); assert.equal(book.threads.length, 2);
assert.ok(writeChats(storage,'alice',book));
const afterRestart=readChats(storage,'alice',now+100);
const third=beginConversation(afterRestart);
assert.equal(afterRestart.threads.length, 2); // previous empty visit is replaced, saved history remains
const recall=recallChats(afterRestart,third.id,'С какой задачи я начинаю сегодня день?',now+100,zone);
assert.equal(recall.length,1); assert.ok(recall[0].content.includes('Smolenka'));
assert.ok(!JSON.stringify(recall).includes('Invented dependency'));
assert.equal(recallChats(afterRestart,third.id,'План на сегодня',now+86400000,zone).length,0);
afterRestart.threads[1].messages[0].recallExcluded=true;
assert.equal(recallChats(afterRestart,third.id,'Smolenka',now+100,zone).length,0);
third.input='Unsent draft'; beginConversation(afterRestart); assert.ok(afterRestart.threads.some(t=>t.input==='Unsent draft'));
assert.equal(recallChats(readChats(storage,'bob',now), 'other', 'Smolenka',now,zone).length,0);
const tomorrowBook={threads:[{id:'past',messages:[{role:'user',content:'Завтра начну со Smolenka',at:now}]}]};
const nextDayRecall=recallChats(tomorrowBook,'new','С чего начинаю сегодня?',now+86400000,zone);
assert.equal(nextDayRecall.length,1);
assert.match(nextDayRecall[0].content,/\[На 2026-10-11\]/);
assert.ok(!nextDayRecall[0].content.includes('Завтра'));
assert.equal(recallChats(tomorrowBook,'new','План',now+86400000*2,zone).length,0);
const largeBook={threads:[{id:'past',messages:Array.from({length:100},(_,i)=>({role:'user',content:'Рабочее предпочтение '+i+' '+ 'x'.repeat(600),at:now-i*1000}))}]};
const limited=recallChats(largeBook,'new','предпочтение',now,zone);
assert.ok(limited.length<=10); assert.ok(limited.reduce((n,m)=>n+m.content.length,0)<=3200);
console.log('Memory regression: actual Smolenka phrase, polite and suffix requests, negation, ambiguity, daily expiry, timezone/month boundary, fresh entry/restart, saved drafts, recall, exclusions and account isolation passed');
