import assert from 'node:assert/strict';
import { renderAssistant } from '../js/ui/views.js';
import { webcrypto } from 'node:crypto';
import { readChats, writeChats, newThread, GREETINGS, greetingText, explicitMemory, appendMemory } from '../js/assistant-chats.js';
globalThis.crypto ||= webcrypto;
const values = new Map();
const storage = { getItem: k => values.get(k) || null, setItem: (k, v) => values.set(k, v) };
storage.setItem('mark:assistant:alice', JSON.stringify([{ role: 'user', content: 'Старый диалог', at: 1 }, { role: 'assistant', content: 'Ответ', at: 2 }]));
const alice = readChats(storage, 'alice', 3);
assert.equal(alice.threads[0].title, 'Старый диалог'); assert.equal(alice.threads[0].messages.length, 2);
const second = newThread(alice.nextGreeting++, 4); alice.threads.unshift(second); alice.activeId = second.id;
alice.memory = appendMemory(alice.memory, explicitMemory('Запомни: я начинаю работу в 10 утра'));
assert.ok(writeChats(storage, 'alice', alice));
const restored = readChats(storage, 'alice', 5);
assert.equal(restored.activeId, second.id); assert.equal(restored.threads.length, 2);
assert.equal(restored.threads[1].messages.length, 2); assert.equal(restored.memory[0], 'я начинаю работу в 10 утра');
assert.equal(readChats(storage, 'bob', 5).memory.length, 0);
assert.equal(readChats(storage, 'bob', 5).threads[0].messages.length, 0);
assert.equal(explicitMemory('Покажи мои задачи'), null);
assert.equal(explicitMemory('не запомни: нет'), null);
assert.equal(appendMemory(restored.memory, restored.memory[0]).length, 1);
assert.equal(appendMemory(Array.from({length:20}, (_,i)=>String(i)), 'extra'), null);
assert.equal(writeChats({ setItem() { throw Error('quota'); } }, 'alice', alice), false);
assert.equal(readChats(storage, null), null);
assert.equal(new Set(GREETINGS).size, 10);
assert.equal(new Set(Array.from({length:10}, (_,i)=>greetingText(i, 'Кирилл'))).size, 10);
assert.ok(greetingText(0, 'Кирилл').includes(', Кирилл'));
assert.ok(!greetingText(0).includes('{n}'));
const markup = renderAssistant({ ui: { assistant: { chat: [], input: '', book: { memory: ['<script>x</script>'], threads: [{id:'safe', title:'<img src=x>', messages:[]}] }, panel:'chats' } }, settings: { assistant_consent_at: 'yes' }, session: {user: {user_metadata: {display_name:'<script>name</script>'}}}, rows: {tasks:[]}, status: {state:'synced', conflicts:[], failed:[]} });
assert.ok(markup.includes('Мои чаты')); assert.ok(markup.includes('Новый чат')); assert.ok(markup.includes('&lt;img src=x&gt;'));
assert.ok(!markup.includes('<script>name</script>'));
console.log('Assistant: migration, separate chats, restart persistence, account isolation, explicit memory, limits, storage failure and ten greetings passed');
