// deno test supabase/functions/_shared/dates_test.ts — даты словами считает сервер.
import { assertEquals } from "jsr:@std/assert@1";
import { datePhrases } from "./dates.ts";

const T = "2026-09-29"; // вторник
const d = (text: string, today = T) => datePhrases(text, today).map((x) => x.date);

Deno.test("относительные дни", () => {
  assertEquals(d("созвон завтра в 11"), ["2026-09-30"]);
  assertEquals(d("послезавтра забрать посылку"), ["2026-10-01"]);
  assertEquals(d("сегодня вечером разобрать почту"), ["2026-09-29"]);
  assertEquals(d("через неделю продлить домен"), ["2026-10-06"]);
  assertEquals(d("через 3 дня"), ["2026-10-02"]);
  assertEquals(d("через две недели"), ["2026-10-13"]);
  assertEquals(d("через день"), ["2026-10-01"]);
});

Deno.test("дни недели: ближайший после сегодня; сегодняшний — через неделю; «следующий» — ещё на неделю", () => {
  assertEquals(d("отчёт до пятницы"), ["2026-10-02"]);
  assertEquals(d("позвонить Ольге в среду в 9 утра"), ["2026-09-30"]);
  assertEquals(d("к понедельнику подготовить КП"), ["2026-10-05"]);
  assertEquals(d("во вторник созвон"), ["2026-10-06"]);
  assertEquals(d("в следующую среду"), ["2026-10-07"]);
  assertEquals(d("в среду и в четверг тренировка в 19"), ["2026-09-30", "2026-10-01"]);
  assertEquals(d("в субботу в 12 уборка"), ["2026-10-03"]);
  assertEquals(d("в воскресенье"), ["2026-10-04"]);
});

Deno.test("числа: этот год, прошедшее — следующий; невозможное — нет", () => {
  assertEquals(d("сдать отчёт в налоговую до 25.10"), ["2026-10-25"]);
  assertEquals(d("до 15 октября подать документы"), ["2026-10-15"]);
  assertEquals(d("3-го декабря"), ["2026-12-03"]);
  assertEquals(d("5 января"), ["2027-01-05"]);
  assertEquals(d("12 октября в 16:00 стоматолог"), ["2026-10-12"]);
  assertEquals(d("1 мая 2027"), ["2027-05-01"]);
  assertEquals(d("30 февраля"), []);
  assertEquals(d("10.05.2027"), ["2027-05-10"]);
});

Deno.test("время не принимается за дату", () => {
  assertEquals(d("в 10:30 встреча"), []);
  assertEquals(d("в 10.30 встреча"), []);
  assertEquals(d("завтра в 25:00 созвон"), ["2026-09-30"]);
  assertEquals(d("купить хлеб"), []);
});

Deno.test("конец месяца и недели", () => {
  assertEquals(d("не забыть оплатить интернет до конца месяца"), ["2026-09-30"]);
  assertEquals(d("до конца недели"), ["2026-10-04"]);
  assertEquals(d("до конца месяца", "2026-12-15"), ["2026-12-31"]);
});
